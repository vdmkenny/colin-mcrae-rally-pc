#!/usr/bin/env python3
"""Compile runtime/shaders/*.vert|frag for SDL_GPU into runtime/gpu_shaders.h.

Each shader is embedded as SPIR-V (Vulkan) and as Metal source (macOS), so building the
game does not need a shader compiler. Run this after editing a shader; needs glslc
(shaderc) and spirv-cross.
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "runtime", "shaders")
OUT = os.path.join(ROOT, "runtime", "gpu_shaders.h")


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + "".join(f"0x{b:02x}," for b in data[i:i + 16]))
    return "\n".join(lines)


def main():
    names = sorted(f for f in os.listdir(SRC) if f.endswith((".vert", ".frag")))
    out = ["// Generated by tools/build_shaders.py from runtime/shaders - do not edit.", "#pragma once",
           "#include <stdint.h>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for name in names:
            ident = name.replace(".", "_")
            spv = os.path.join(tmp, name + ".spv")
            msl = os.path.join(tmp, name + ".msl")
            subprocess.check_call(["glslc", "-O", "-o", spv, os.path.join(SRC, name)])
            subprocess.check_call(["spirv-cross", spv, "--msl", "--msl-version", "20000", "--output", msl])
            for suffix, path in (("spv", spv), ("msl", msl)):
                data = open(path, "rb").read()
                out.append(f"static const uint8_t {ident}_{suffix}[{len(data)}] = {{")
                out.append(c_bytes(data))
                out.append("};")
            out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT} ({len(names)} shaders)")


if __name__ == "__main__":
    sys.exit(main())
